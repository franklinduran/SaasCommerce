import * as SelectPrimitive from '@radix-ui/react-select'
import { CheckIcon, ChevronDownIcon, ChevronUpIcon } from 'lucide-react'
import { cn } from '@/shared/utils/cn'

export const Select         = SelectPrimitive.Root
export const SelectGroup    = SelectPrimitive.Group
export const SelectValue    = SelectPrimitive.Value

export function SelectTrigger({
  className,
  children,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Trigger>) {
  return (
    <SelectPrimitive.Trigger
      className={cn(
        'flex h-10 w-full min-w-0 items-center justify-between gap-2 rounded-md bg-white px-3 text-sm font-medium text-stone-900 shadow-[0_0_0_1px_rgb(214_211_209)] outline-none transition',
        'placeholder:text-stone-400',
        'hover:bg-stone-50 active:bg-stone-100',
        'focus:shadow-[0_0_0_1px_rgb(28_25_23)] focus:ring-2 focus:ring-stone-900/15',
        'disabled:cursor-not-allowed disabled:bg-stone-100 disabled:text-stone-500',
        '[&>span]:truncate [&>span]:text-left',
        className,
      )}
      {...props}
    >
      {children}
      <SelectPrimitive.Icon asChild>
        <ChevronDownIcon className="size-4 shrink-0 text-stone-500" />
      </SelectPrimitive.Icon>
    </SelectPrimitive.Trigger>
  )
}

